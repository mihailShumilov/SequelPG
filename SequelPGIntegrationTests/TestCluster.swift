import Foundation
import XCTest
@testable import SequelPG

/// Mirror of `test-db/test-env.json` — the single source of truth for the
/// Docker test cluster's ports, roles and passwords.
struct TestClusterConfig: Decodable {
    struct Credentials: Decodable {
        let user: String
        let password: String
    }

    struct Server: Decodable {
        let port: Int
        let major: Int
        let ssl: Bool
    }

    struct SSH: Decodable {
        let port: Int
        let user: String
        let password: String
        let targetHost: String
        let targetPort: Int
    }

    let host: String
    let database: String
    let admin: Credentials
    let roles: [String: Credentials]
    let servers: [String: Server]
    let ssh: SSH
}

/// Access to the live test cluster started by `make -C test-db up`.
///
/// When the cluster isn't running, `require(...)` skips the test — unless
/// `SEQUELPG_REQUIRE_CLUSTER=1` is set (the `test-db` Makefile sets it), in
/// which case it fails, so a broken cluster can never pass silently.
enum TestCluster {
    enum Server: String, CaseIterable {
        case pg18, pg16, pg13
    }

    enum Role: String, CaseIterable {
        case scram, md5, trust, readonly, sslonly
    }

    static let repoRoot = URL(fileURLWithPath: #filePath)
        .deletingLastPathComponent()
        .deletingLastPathComponent()
    static let testDBDirectory = repoRoot.appendingPathComponent("test-db")
    static let generatedDirectory = testDBDirectory.appendingPathComponent(".generated")

    static let config: TestClusterConfig = {
        let url = testDBDirectory.appendingPathComponent("test-env.json")
        do {
            return try JSONDecoder().decode(TestClusterConfig.self, from: Data(contentsOf: url))
        } catch {
            fatalError("Cannot read \(url.path): \(error)")
        }
    }()

    static var host: String { config.host }
    static var database: String { config.database }
    static let otherDatabase = "sequelpg_test_other"

    static func port(_ server: Server) -> Int { config.servers[server.rawValue]!.port }
    static func major(_ server: Server) -> Int { config.servers[server.rawValue]!.major }
    static func hasSSL(_ server: Server) -> Bool { config.servers[server.rawValue]!.ssl }

    static func user(_ role: Role) -> String { config.roles[role.rawValue]!.user }

    /// `nil` for roles without a password (trust).
    static func password(_ role: Role) -> String? {
        let pw = config.roles[role.rawValue]!.password
        return pw.isEmpty ? nil : pw
    }

    // MARK: SSH material (generated by test-db/scripts/gen-assets.sh)

    static var sshClientKeyPath: String { generatedDirectory.appendingPathComponent("ssh/client_ed25519").path }
    static var sshWrongKeyPath: String { generatedDirectory.appendingPathComponent("ssh/wrong_ed25519").path }
    static var sshKnownHostsPath: String { generatedDirectory.appendingPathComponent("ssh/known_hosts").path }
    static var sshHostPublicKeyPath: String {
        generatedDirectory.appendingPathComponent("ssh/ssh_host_ed25519_key.pub").path
    }

    // MARK: Availability

    static var clusterRequired: Bool {
        ProcessInfo.processInfo.environment["SEQUELPG_REQUIRE_CLUSTER"] == "1"
    }

    /// Skips (or fails, see type docs) when any of `servers` is unreachable.
    static func require(_ servers: [Server] = Server.allCases, ssh: Bool = false) throws {
        var missing = servers.filter { !isPortOpen(port($0)) }.map(\.rawValue)
        if ssh, !isPortOpen(config.ssh.port) { missing.append("sshd") }
        guard !missing.isEmpty else { return }
        let message = "Test cluster not reachable (\(missing.joined(separator: ", "))). Run: make -C test-db up"
        if clusterRequired {
            XCTFail(message)
            throw XCTSkip(message) // stop the test body after recording the failure
        }
        throw XCTSkip(message)
    }

    static func isPortOpen(_ port: Int) -> Bool {
        let fd = socket(AF_INET, SOCK_STREAM, IPPROTO_TCP)
        guard fd >= 0 else { return false }
        defer { close(fd) }
        var addr = sockaddr_in()
        addr.sin_len = UInt8(MemoryLayout<sockaddr_in>.size)
        addr.sin_family = sa_family_t(AF_INET)
        addr.sin_port = UInt16(port).bigEndian
        addr.sin_addr.s_addr = inet_addr("127.0.0.1")
        return withUnsafePointer(to: &addr) {
            $0.withMemoryRebound(to: sockaddr.self, capacity: 1) {
                Darwin.connect(fd, $0, socklen_t(MemoryLayout<sockaddr_in>.size)) == 0
            }
        }
    }

    // MARK: Profiles

    static func profile(
        _ server: Server = .pg18,
        role: Role = .scram,
        sslMode: SSLMode = .off,
        database: String? = nil,
        host: String? = nil
    ) -> ConnectionProfile {
        ConnectionProfile(
            name: "\(server.rawValue)-\(role.rawValue)-\(sslMode.rawValue)",
            host: host ?? self.host,
            port: port(server),
            database: database ?? self.database,
            username: user(role),
            sslMode: sslMode
        )
    }

    /// A profile that reaches pg18 through the SSH bastion. The DB host is
    /// the compose service name — resolved on the bastion, not locally.
    static func sshProfile(
        auth: SSHAuthMethod = .keyFile,
        keyPath: String? = nil,
        role: Role = .scram,
        sslMode: SSLMode = .off,
        database: String? = nil
    ) -> ConnectionProfile {
        ConnectionProfile(
            name: "ssh-\(auth.rawValue)",
            host: config.ssh.targetHost,
            port: config.ssh.targetPort,
            database: database ?? self.database,
            username: user(role),
            sslMode: sslMode,
            useSSHTunnel: true,
            sshHost: config.host,
            sshPort: config.ssh.port,
            sshUser: config.ssh.user,
            sshAuthMethod: auth,
            sshKeyPath: auth == .keyFile ? (keyPath ?? sshClientKeyPath) : ""
        )
    }

    // MARK: Clients

    /// A connected `DatabaseClient`. Callers own it and should disconnect it
    /// (`IntegrationTestCase.connect` does so automatically).
    static func connect(
        _ server: Server = .pg18,
        role: Role = .scram,
        sslMode: SSLMode = .off,
        database: String? = nil
    ) async throws -> DatabaseClient {
        let client = DatabaseClient()
        try await client.connect(
            profile: profile(server, role: role, sslMode: sslMode, database: database),
            password: password(role),
            sshPassword: nil
        )
        return client
    }
}

// MARK: - Query helpers

extension DatabaseClient {
    /// Runs `sql` with generous limits and returns the result.
    @discardableResult
    func exec(_ sql: String, maxRows: Int = 10000, timeout: TimeInterval = 30) async throws -> QueryResult {
        try await runQuery(sql, maxRows: maxRows, timeout: timeout)
    }

    /// First cell of the first row rendered as text (`nil` for SQL NULL or no rows).
    func scalar(_ sql: String) async throws -> String? {
        let result = try await exec(sql, maxRows: 1)
        guard let cell = result.rows.first?.first, case let .text(value) = cell else { return nil }
        return value
    }
}

extension QueryResult {
    /// Column `name` of every row, `nil` for SQL NULL.
    func column(_ name: String) -> [String?] {
        guard let index = columns.firstIndex(of: name) else { return [] }
        return rows.map { row in
            if case let .text(value) = row[index] { return value }
            return nil
        }
    }
}
